import JSZip from 'jszip';

/**
 * Computer Vision Exporters: YOLO, COCO JSON, Pascal VOC, and Classification CSV
 */

export function exportCocoJson(images, classes) {
  const categories = classes.map((c, i) => ({
    id: i + 1,
    name: c.name,
    supercategory: 'none',
  }));

  const classToId = {};
  classes.forEach((c, i) => {
    classToId[c.name] = i + 1;
  });

  const cocoImages = [];
  const cocoAnnotations = [];
  let annIdCounter = 1;

  images.forEach((img, imgIdx) => {
    const imageId = imgIdx + 1;
    cocoImages.push({
      id: imageId,
      width: img.width || 800,
      height: img.height || 600,
      file_name: img.name,
    });

    (img.boxes || []).forEach((b) => {
      const categoryId = classToId[b.label] || 1;
      const x = Math.round(b.x);
      const y = Math.round(b.y);
      const w = Math.round(b.width);
      const h = Math.round(b.height);

      cocoAnnotations.push({
        id: annIdCounter++,
        image_id: imageId,
        category_id: categoryId,
        bbox: [x, y, w, h],
        area: w * h,
        segmentation: [],
        iscrowd: 0,
      });
    });
  });

  const cocoData = {
    info: {
      year: new Date().getFullYear(),
      version: '1.0',
      description: 'Exported from EdgeVision (EdgeLabel Suite) — 100% Client-Side',
      contributor: 'EdgeLabel',
      date_created: new Date().toISOString(),
    },
    licenses: [{ id: 1, name: 'Local Dataset', url: '' }],
    images: cocoImages,
    annotations: cocoAnnotations,
    categories,
  };

  const jsonStr = JSON.stringify(cocoData, null, 2);
  const blob = new Blob([jsonStr], { type: 'application/json' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `edgevision_coco_${Date.now()}.json`;
  a.click();
  URL.revokeObjectURL(url);
}

export async function exportYoloZip(images, classes) {
  const zip = new JSZip();

  // classes.txt
  const classesContent = classes.map((c) => c.name).join('\n');
  zip.file('classes.txt', classesContent);

  // dataset.yaml
  const yamlContent = [
    '# YOLO Dataset configuration generated by EdgeVision',
    'path: .',
    'train: images/train',
    'val: images/val',
    'names:',
    ...classes.map((c, i) => `  ${i}: ${c.name}`),
  ].join('\n');
  zip.file('dataset.yaml', yamlContent);

  const labelsFolder = zip.folder('labels');
  const classToIdx = {};
  classes.forEach((c, i) => {
    classToIdx[c.name] = i;
  });

  images.forEach((img) => {
    const baseName = img.name.replace(/\.[^/.]+$/, '');
    const imgWidth = img.width || 800;
    const imgHeight = img.height || 600;

    const yoloLines = (img.boxes || []).map((b) => {
      const clsIdx = classToIdx[b.label] ?? 0;
      // YOLO normalized: class_id x_center y_center width height (0.0 to 1.0)
      const xCenter = (b.x + b.width / 2) / imgWidth;
      const yCenter = (b.y + b.height / 2) / imgHeight;
      const normWidth = b.width / imgWidth;
      const normHeight = b.height / imgHeight;

      const clamp = (v) => Math.max(0, Math.min(1, v)).toFixed(6);

      return `${clsIdx} ${clamp(xCenter)} ${clamp(yCenter)} ${clamp(normWidth)} ${clamp(normHeight)}`;
    });

    labelsFolder.file(`${baseName}.txt`, yoloLines.join('\n'));
  });

  const content = await zip.generateAsync({ type: 'blob' });
  const url = URL.createObjectURL(content);
  const a = document.createElement('a');
  a.href = url;
  a.download = `edgevision_yolo_${Date.now()}.zip`;
  a.click();
  URL.revokeObjectURL(url);
}

export function exportClassificationCsv(images) {
  const rows = ['"File Name","Classification","Bounding Boxes Count"'];
  images.forEach((img) => {
    const boxesCount = img.boxes ? img.boxes.length : 0;
    const cls = img.classification || 'Unclassified';
    rows.push(`"${img.name}","${cls}",${boxesCount}`);
  });
  const csvContent = rows.join('\n');
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `edgevision_classifications_${Date.now()}.csv`;
  a.click();
  URL.revokeObjectURL(url);
}
